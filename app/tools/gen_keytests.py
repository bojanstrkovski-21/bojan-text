# Generates src/app/keytests.rs: every shortcut shown in the menus with the command it must run.
import io, re

m = io.open('src/app/menus.rs', encoding='utf-8').read()
pairs = []
# item(ui, label, "Shortcut", "id", &mut cmd)
for sc, cid in re.findall(r',\s*"([^"]*)",\s*"([a-z_0-9]+)",\s*&mut cmd\)', m):
    if sc and (sc, cid) not in pairs:
        pairs.append((sc, cid))
# check(ui, label, "Shortcut", on, "id", &mut cmd) and the Layout tuples
for sc, cid in re.findall(r'check\(ui, "[^"]*", "([^"]+)", [^,]+, "([a-z_0-9]+)", &mut cmd\)', m):
    if (sc, cid) not in pairs:
        pairs.append((sc, cid))
for sc, g, c in re.findall(r'\("[^"]+", (\d), (\d), "(Alt\+Shift\+\d)"\)', m):
    pairs.append((c if False else g and "", ""))  # placeholder, replaced below
pairs = [p for p in pairs if p[0]]
for label, g, c, sc in re.findall(r'\("([^"]+)", (\d), (\d), "(Alt\+Shift\+\d)"\)', m):
    pairs.append((sc, "layout:%s:%s" % (g, c)))
# numbered families written with format!
for n in range(1, 11):
    pairs.append(("Alt+%d" % (n % 10), "tab:%d" % n))
for n in range(1, 5):
    pairs.append(("Ctrl+%d" % n, "focus_group:%d" % n))
    pairs.append(("Ctrl+Shift+%d" % n, "move_group:%d" % n))
# command ids shown differently in the menu
extra = [("Ctrl+Shift+P", "palette_cmd")]
for e in extra:
    if e not in pairs:
        pairs.append(e)

skip_ids = {"exit"}
out = ["// Generated by tools/gen_keytests.py from the menus. Used only by --test-keys.",
       "pub const KEY_TESTS: &[(&str, &str)] = &["]
for sc, cid in pairs:
    if cid in skip_ids or sc in ("Escape",):
        continue
    out.append('    ("%s", "%s"),' % (sc, cid))
out.append("];")
io.open('src/app/keytests.rs', 'w', encoding='utf-8', newline='\n').write("\n".join(out) + "\n")
print(len(pairs), "shortcuts")
